def norm(s):
    s = s.replace("\u0301", "")            # знаки ударения не мешают якорям
    return s.lower().replace("’", "'").replace("ʼ", "'")


def analyse(path):
    raw = open(path, encoding="utf-8").read()
    lines = [l for l in raw.splitlines() if l.strip() and not l.startswith("[")]
    text = norm(" ".join(lines))
    V = set("аеєиіїоуюя")
    words = re.findall(r"[а-яіїєґ']+", text)
    syl = sum(sum(c in V for c in w) for w in words)

    # 1. покрытие битов
    hit, miss = [], []
    for n, t, fn, mean, anchors, crit in BEATS:
        ok = all(re.search(a, text) for a in anchors)
        (hit if ok else miss).append((n, t, fn, mean, crit))
    wsum = sum(c for *_, c in [(b[0], b[5]) and b for b in BEATS] ) if False else sum(b[5] for b in BEATS)
    whit = sum(c for *_, c in [(x[0], x[4]) for x in hit]) if False else sum(x[4] for x in hit)
    cover = whit / wsum

    # 2. конкретика
    facts_ok = {k: bool(re.search(v, text)) for k, v in FACTS.items()}
    facts_ok["ИМЯ ПРОДУКТА в CTA"] = bool(re.search(r"[Кк]рем називається\s+[«\"']?[A-ZА-ЯІЇЄҐ]", raw))
    facts = sum(facts_ok.values()) / len(facts_ok)

    # 3. эмоциональные точки
    emo_ok = {k: bool(re.search(v, text)) for k, v in EMO.items()}
    emo = sum(emo_ok.values()) / len(emo_ok)

    # 4. порядок битов (совпадает ли последовательность попаданий с эталоном)
    pos = []
    for n, t, fn, mean, anchors, crit in BEATS:
        p = None
        for a in anchors:
            m = re.search(a, text)
            if m:
                p = m.start() if p is None else min(p, m.start())
        if p is not None:
            pos.append((n, p))
    order = 1.0
    if len(pos) > 3:
        rk = np.argsort([p for _, p in pos])
        ideal = np.arange(len(pos))
        order = float(max(0.0, np.corrcoef(rk, ideal)[0, 1]))

    # 5. бюджет: слогов должно хватать на 194 с при 195 слог/мин, но не переливать
    need = 194 / 60 * 200          # с вокальным сидом доказано 207 слог/мин
    budget = max(0.0, 1 - max(0, abs(syl - need) - need * 0.06) / (need * 0.22))

    # 6. CTA полный: назван продукт + ссылка + условие
    cta = sum(bool(re.search(a, text)) for _, _, fn, _, ancs, _ in [b for b in BEATS if b[2] == "CTA"] for a in ancs)
    cta_beats = [b for b in BEATS if b[2] == "CTA"]
    cta_ok = sum(all(re.search(a, text) for a in b[4]) for b in cta_beats) / len(cta_beats)

    bad_hits = {k: bool(re.search(v, text)) for k, v in BAD.items()}
    bad_hits["вітамін це строчной (нужно «вітамін С» или фонетическое «вітамін Це»)"] = bool(re.search(r"вітамін це\b", raw))
    nbad = sum(bad_hits.values())
    lang = max(0.0, 1 - nbad / 6.0)

    scores = {
        "язык и локализация": lang,
        "покрытие битов": cover,
        "конкретика": facts,
        "эмоц. точки": emo,
        "порядок": order,
        "бюджет слогов": budget,
        "CTA": cta_ok,
    }
    Wg = {"язык и локализация": 3.0, "покрытие битов": 3.0, "конкретика": 2.2, "эмоц. точки": 1.3,
          "порядок": 0.6, "бюджет слогов": 0.7, "CTA": 1.7}
    total = sum(scores[k] * Wg[k] for k in Wg) / sum(Wg.values()) * 10
    return dict(path=path, lines=len(lines), words=len(words), syl=syl, scores=scores, total=total,
                miss=miss, facts_ok=facts_ok, emo_ok=emo_ok,
                bad=[k for k, v in bad_hits.items() if v])


if __name__ == "__main__":
    res = []
    for p in sys.argv[1:]:
        r = analyse(p)
        res.append(r)
